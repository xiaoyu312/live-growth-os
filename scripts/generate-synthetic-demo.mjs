import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
// Independently authored fixed demonstration values, never derived from a record.
const seed = 20300101;
const profiles = Object.fromEntries(['morning', 'afternoon', 'evening'].map((name, i) => [
  `historical_${name}`, {
    timeLabel: `Synthetic ${name}`, sampleSize: 0,
    perMinute: { roomEnterUv: 20 + i * 4, roomImpressionUv: 100 + i * 20, productImpressionUv: 16 + i * 4, productClickUv: 4 + i, paidBuyerCount: 0.5 + i * 0.25 },
    grossGmvFen: 150000 + i * 30000, adSpendFen: 60000 + i * 10000
  }
]));
const metadata = { classification: 'independently_synthetic', seed, startAt: '2030-01-01T00:00:00.000Z', profiles,
  note: 'No source business rows, statistics, people, products, transcripts or identifiers were read by this generator.' };
mkdirSync(resolve(root, 'examples'), { recursive: true });
writeFileSync(resolve(root, 'examples/synthetic-scenarios.json'), JSON.stringify(metadata, null, 2) + '\n');
const header = `// Generated by scripts/generate-synthetic-demo.mjs. Independent synthetic values.\n// Legacy export names are retained only for the simulator API; these are NOT historical statistics.\nexport interface HistoricalTimeProfile { timeLabel: string; sampleSize: number; perMinute: { roomEnterUv: number; roomImpressionUv: number; productImpressionUv: number; productClickUv: number; paidBuyerCount: number }; grossGmvFen: number; adSpendFen: number; }\nexport const HISTORICAL_CONCURRENT_VIEWERS_CALIBRATION = { median: 100, syntheticJitter: 3 } as const;\n`;
mkdirSync(resolve(root, 'packages/source-adapters/src/calibrations'), { recursive: true });
writeFileSync(resolve(root, 'packages/source-adapters/src/calibrations/historical.ts'), header + 'export const HISTORICAL_TIME_PROFILES: Record<string, HistoricalTimeProfile> = ' + JSON.stringify(profiles, null, 2) + ';\n');
console.log('Generated independent synthetic demonstration profiles (seed ' + seed + ').');
